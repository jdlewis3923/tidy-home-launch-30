import { createClient } from 'https://esm.sh/@supabase/supabase-js@2.45.4';
import { corsHeaders } from 'npm:@supabase/supabase-js@2/cors';
import { z } from 'https://deno.land/x/zod@v3.22.4/mod.ts';
import { linkedinReceiptValid } from '../_shared/linkedin-contract.ts';
const schema=z.object({post_id:z.string().uuid(),linkedin_urn:z.string().max(255),linkedin_url:z.string().url().max(1000),status:z.literal('posted')}).strict();
const json=(body:unknown,status=200)=>new Response(JSON.stringify(body),{status,headers:{...corsHeaders,'Content-Type':'application/json'}});
Deno.serve(async req=>{
 if(req.method==='OPTIONS')return new Response('ok',{headers:corsHeaders});
 if(req.method!=='POST')return json({error:'POST required'},405);
 const parsed=schema.safeParse(await req.json().catch(()=>null));if(!parsed.success)return json({error:'Invalid delivery receipt'},400);
 const input=parsed.data;
 if(!linkedinReceiptValid(input.linkedin_urn,input.linkedin_url))return json({error:'A valid LinkedIn URN and post URL are required'},400);
 const token=z.string().uuid().safeParse(new URL(req.url).searchParams.get('receipt'));
 if(!token.success)return json({error:'Invalid receipt authorization'},403);
 const url=Deno.env.get('SUPABASE_URL'),key=Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');if(!url||!key)return json({error:'Configuration missing'},500);
 const sb=createClient(url,key,{auth:{persistSession:false}});
 const {error}=await sb.rpc('linkedin_confirm_receipt',{_post:input.post_id,_token:token.data,_urn:input.linkedin_urn,_url:input.linkedin_url});
 if(error)return json({error:error.message},error.message.includes('authorization')?403:409);
 return json({confirmed:true,post_id:input.post_id,linkedin_url:input.linkedin_url});
});